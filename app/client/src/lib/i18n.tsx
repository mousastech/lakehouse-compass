const DICTS: Record<Lang, Dict> = { en, 'pt-BR': ptBR };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const Ctx = createContext<I18nCtx | null>(null);
const LANG_KEY = 'compass_lang';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return localStorage.getItem(LANG_KEY) === 'pt-BR' ? 'pt-BR' : 'en';
    } catch {
      return 'en';
    }
  });

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      // ignore
    }
  };

  const t = (key: string): string => DICTS[lang][key] ?? en[key] ?? key;

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

export function useT(): (key: string) => string {
  return useI18n().t;
}

export function LanguageSwitcher({ compact = false }: { compact?: boolean }) {
  const { lang, setLang } = useI18n();
  const langs: Lang[] = ['en', 'pt-BR'];
  return (
    <div className="flex gap-1">
      {langs.map((l) => (
        <button
          key={l}
          type="button"
          onClick={() => setLang(l)}
          className={`rounded-md px-2 py-1 text-xs font-medium transition-colors ${
            lang === l
              ? 'bg-sidebar-primary text-sidebar-primary-foreground'
              : 'text-sidebar-foreground/70 hover:bg-sidebar-accent'
          }`}
        >
          {compact ? l.slice(0, 2).toUpperCase() : l === 'en' ? 'EN' : 'PT-BR'}
        </button>
      ))}
    </div>
  );
}
